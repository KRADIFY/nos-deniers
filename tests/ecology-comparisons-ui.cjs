const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
(async()=>{
 const out=path.resolve(__dirname,'../reports/comparaisons-ecologie-20260909/ui');await fs.mkdir(out,{recursive:true});
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 try{
  const page=await browser.newPage({baseURL:'http://127.0.0.1:8552',viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const ready=async()=>{await page.waitForFunction(()=>document.querySelector('#loading').hidden&&!document.querySelector('#export').disabled);};
  const go=async q=>{await page.goto('/?'+q);await ready();};
  const api=async()=>await (await page.request.get('/api/explorer?'+new URL(page.url()).searchParams)).json();
  await go('start=2024&end=2024&scope=TA&measure=CP&budget=BG');
  const original=await api(),sw=page.locator('[data-exclude="TA/345"]');
  assert.equal(await sw.getAttribute('role'),'switch');assert.equal(await sw.getAttribute('aria-checked'),'true');
  const before=original.totals[0].EXEC.nominal_cents,part=original.rows.find(r=>r.id==='TA/345').series[0].EXEC.nominal_cents;
  await sw.focus();await page.keyboard.press('Space');await ready();
  assert.equal(await sw.getAttribute('aria-checked'),'false');assert.equal(await sw.evaluate(e=>e===document.activeElement),true);
  assert.equal((await api()).totals[0].EXEC.nominal_cents,before-part);
  assert.equal(await page.locator('[data-restore="TA/345"]').getAttribute('role'),'switch');
  await sw.press('Enter');await ready();assert.equal((await api()).totals[0].EXEC.nominal_cents,before);
  await sw.click();await ready();await page.locator('[data-restore="TA/345"]').click();await ready();assert.equal((await api()).totals[0].EXEC.nominal_cents,before);
  await go('start=2021&end=2024&scope=TA&measure=AE&budget=BG&constant=1&base=2017');
  await page.locator('[data-ecology-preset="selected"]').click();await ready();
  const p=(await api()).parameters;
  assert.equal(p.measure,'AE');assert.equal(p.base,2017);assert.equal(p.constant,true);assert.equal(p.start,2021);assert.equal(p.end,2024);
  assert.deepEqual(p.exclude,['TA/345','TA/235']);assert.equal(p.topic_mode,'without');
  await page.locator('[data-ecology-preset="full"]').click();await ready();
  await page.locator('[data-mode="evolution"]').click();
  const rate=page.locator('[data-evolution="real_yoy"][data-year="2024"][data-cell-scope="TA"]');
  const text=await rate.innerText();assert(text.includes('%'));
  await rate.click();await page.locator('#source-dialog[open]').waitFor();assert((await page.locator('#source-content').innerText()).includes('IPC annuel'));
  await page.locator('#source-content button[data-year="2023"]').click();await page.waitForFunction(()=>document.querySelector('#source-content').textContent.includes('PDF')||document.querySelector('#source-content').textContent.includes('Source'));
  await page.locator('#close-source').click();await page.locator('#constant').uncheck();await ready();assert.equal(await rate.innerText(),text);
  await page.locator('#credits-table').screenshot({path:path.join(out,'variations-annuelles.png')});
  // A missing policy figure stays visible, labelled and unavailable, never silently removed or zeroed.
  await go('start=2024&end=2025&scope=TA&measure=CP&budget=BG&topic=maprimerenov&topic_mode=only');
  assert((await page.locator('#credits-table').innerText()).includes('Données non disponibles'));
  assert.equal((await api()).totals[1].EXEC.value,null);
  await go('start=2025&end=2025&scope=TA&measure=CP&budget=BG&topic=maprimerenov&topic_mode=only');
  const missingSwitch=page.locator('[data-exclude="TA/174"]');assert(await missingSwitch.isVisible());assert(await missingSwitch.isDisabled());
  await page.locator('#credits-table').screenshot({path:path.join(out,'donnees-manquantes.png')});
  await go('start=2024&end=2024&scope=TA&measure=CP&budget=BG');
  await page.locator('[data-exclude="TA/345"]').click();await ready();
  await page.locator('#credits-table').screenshot({path:path.join(out,'interrupteurs.png')});
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(300);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await page.locator('[data-exclude="TA/345"]').scrollIntoViewIfNeeded();await page.screenshot({path:path.join(out,'mobile.png')});
  await page.locator('[data-mode="evolution"]').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  assert.deepEqual(errors,[]);await fs.writeFile(path.join(out,'validation.json'),JSON.stringify({passed:true,errors,keyboard:true,selectionReconciled:true,missingVisible:true,mobile:true,realRateIndependentOfDisplay:true},null,2));
  console.log('Ecology comparisons and category switches UI passed');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
